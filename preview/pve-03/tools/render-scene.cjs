'use strict';
/*
 * PVE-03 — offline renderer for the text-free scene layers.
 * Build tool only: the preview itself never loads three.js.
 *
 * Usage (from the repository root):
 *   npm install --prefix /tmp/pve03-three three@0.170.0
 *   THREE_DIR=/tmp/pve03-three/node_modules/three node preview/pve-03/tools/render-scene.cjs
 *
 * Output (preview/pve-03/assets/):
 *   scene-desktop-{1330,2660}.{webp,jpg}   16:9 composition
 *   scene-mobile-{540,1080}.{webp,jpg}     9:16 composition
 *   scene-anchors.js                        normalised object anchors per composition
 * Requires Playwright + Chromium (software WebGL via SwiftShader is sufficient).
 */
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');

const TOOLS = __dirname;
const OUT = path.join(__dirname, '..', 'assets');
const THREE_DIR = process.env.THREE_DIR;
if (!THREE_DIR || !fs.existsSync(path.join(THREE_DIR, 'build', 'three.module.js'))) {
  console.error('Set THREE_DIR to an installed three@0.170.0 package directory.');
  process.exit(2);
}
const { chromium } = require(require.resolve('playwright', { paths: [process.cwd(), __dirname] }));

const TYPES = { '.html': 'text/html', '.js': 'text/javascript' };
function serve() {
  return new Promise(resolve => {
    const srv = http.createServer((req, res) => {
      const u = decodeURIComponent(new URL(req.url, 'http://x').pathname);
      const file = u.startsWith('/three/') ? path.join(THREE_DIR, u.slice(7)) : path.join(TOOLS, u);
      const root = u.startsWith('/three/') ? THREE_DIR : TOOLS;
      if (!path.resolve(file).startsWith(path.resolve(root)) || !fs.existsSync(file)) { res.writeHead(404); return res.end(); }
      res.writeHead(200, { 'content-type': TYPES[path.extname(file)] || 'application/octet-stream' });
      fs.createReadStream(file).pipe(res);
    }).listen(0, '127.0.0.1', () => resolve(srv));
  });
}

const JOBS = [
  { layout: 'desktop', w: 2660, h: 1496, sizes: [2660, 1330] },
  { layout: 'mobile', w: 1080, h: 1920, sizes: [1080, 540] }
];

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const srv = await serve();
  const port = srv.address().port;
  const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const anchors = {};
  try {
    for (const job of JOBS) {
      const page = await browser.newPage({ viewport: { width: 800, height: 600 } });
      page.on('console', m => { if (m.type() === 'error') console.error('[scene]', m.text()); });
      page.on('pageerror', e => { console.error('[scene] pageerror', e.message); });
      await page.goto(`http://127.0.0.1:${port}/scene.html?layout=${job.layout}&w=${job.w}&h=${job.h}`);
      await page.waitForFunction('window.__done === true', null, { timeout: 600000 });
      anchors[job.layout] = await page.evaluate('window.__anchors');
      for (const size of job.sizes) {
        const h = Math.round(job.h * size / job.w);
        const out = await page.evaluate(([w, h]) => {
          const src = document.querySelector('canvas');
          const c = document.createElement('canvas'); c.width = w; c.height = h;
          const g = c.getContext('2d'); g.imageSmoothingEnabled = true; g.imageSmoothingQuality = 'high';
          g.drawImage(src, 0, 0, w, h);
          return { webp: c.toDataURL('image/webp', 0.8), jpg: c.toDataURL('image/jpeg', 0.82) };
        }, [size, h]);
        for (const [ext, data] of Object.entries(out)) {
          const file = path.join(OUT, `scene-${job.layout}-${size}.${ext}`);
          fs.writeFileSync(file, Buffer.from(data.split(',')[1], 'base64'));
          console.log(`${path.relative(process.cwd(), file)}  ${size}x${h}  ${(fs.statSync(file).size / 1024).toFixed(0)} KiB`);
        }
      }
      await page.close();
    }
  } finally {
    await browser.close();
    srv.close();
  }
  const js = '/* Generated by tools/render-scene.cjs — normalised (0..1) positions of objects in each scene layer. */\n' +
    '(function (root) {\n  \'use strict\';\n  const ANCHORS = ' + JSON.stringify(anchors, null, 2).replace(/\n/g, '\n  ') + ';\n' +
    '  if (typeof module === \'object\' && module.exports) module.exports = ANCHORS;\n  else root.EhPve03Anchors = ANCHORS;\n' +
    '})(typeof globalThis !== \'undefined\' ? globalThis : this);\n';
  fs.writeFileSync(path.join(OUT, 'scene-anchors.js'), js);
  console.log('anchors', JSON.stringify(anchors));
})().catch(e => { console.error(e); process.exit(1); });
